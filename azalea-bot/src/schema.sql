-- Same thing, narrowed to one name_dict id. The GIN index on name_ids turns
-- "everything Herobrine was ever part of" into a scan of the few buckets that
-- actually mention them instead of the whole archive.
--
-- nid may be NULL, meaning "every name". That exists so the commands with an
-- optional player argument -- /chat, /keyword -- can be one query instead of
-- two, and still prune when a player is actually given.
CREATE OR REPLACE FUNCTION chat_rows_for_name(nid int, lo timestamptz, hi timestamptz)
RETURNS TABLE (id bigint, received_at timestamptz, session_id int, sender_id int,
               subject_id int, killer_id int, source "char", kind "char", plain_text text)
LANGUAGE sql STABLE PARALLEL SAFE AS $fn$
  SELECT c.id, c.received_at, c.session_id, c.sender_id, c.subject_id,
         c.killer_id, c.source, c.kind, c.plain_text
  FROM chat_messages_raw c
  WHERE c.received_at >= lo AND c.received_at < hi
    AND (nid IS NULL OR c.sender_id = nid OR c.subject_id = nid OR c.killer_id = nid)
  UNION ALL
  SELECT r.id, r.received_at, r.session_id, r.sender_id, r.subject_id,
         r.killer_id, r.source, r.kind, r.plain_text
  FROM chat_archive a
  CROSS JOIN LATERAL unnest(
      convert_from(zstd_decompress(a.ids),         'UTF8')::bigint[],
      convert_from(zstd_decompress(a.received_at), 'UTF8')::timestamptz[],
      convert_from(zstd_decompress(a.session_id),  'UTF8')::int[],
      convert_from(zstd_decompress(a.sender_id),   'UTF8')::int[],
      convert_from(zstd_decompress(a.subject_id),  'UTF8')::int[],
      convert_from(zstd_decompress(a.killer_id),   'UTF8')::int[],
      convert_from(zstd_decompress(a.source),      'UTF8')::"char"[],
      convert_from(zstd_decompress(a.kind),        'UTF8')::"char"[],
      convert_from(zstd_decompress(a.plain_text),  'UTF8')::text[]
    ) AS r(id, received_at, session_id, sender_id, subject_id, killer_id,
           source, kind, plain_text)
  WHERE (nid IS NULL OR a.name_ids @> ARRAY[nid])
    AND a.max_at >= lo AND a.min_at < hi
    AND r.received_at >= lo AND r.received_at < hi
    AND (nid IS NULL OR r.sender_id = nid OR r.subject_id = nid OR r.killer_id = nid)
$fn$;

