-- Schema for the azalea chat logger (r11).
--
-- Storage shape, and why:
--   * chat_messages_raw / player_events_raw are the physical tables. Names are
--     stored once in `name_dict` and referenced by INT4, because writing
--     "Herobrine" out again on every row is most of what a chat log costs.
--   * Fixed-width columns are ordered so there is no alignment padding
--     (8,8,4,4,4,4,1,1 packs exactly).
--   * No primary key and no foreign key on the log tables. The PK btree cost
--     ~31 bytes/row for an index only the bridge cursor read, and an FK is
--     enforced by a per-row trigger on every insert.
--   * `chat_messages` / `player_events` survive as views with the old column
--     names, so readers written against the old schema keep working.
--   * Counters live in stats_daily / player_daily. The old per-row triggers
--     serialised every writer behind one row lock.
--
--   * Only the last few days live as rows. Everything older is packed by day
--     into zstd column buckets (chat_archive / events_archive), which costs
--     ~15 bytes a row against ~138 live. `archive_closed_days(keep_days)` does
--     the packing; the accessors below hide which side a row is on.
--
-- Existing databases get here via deploy/migrate-r11.sh.

CREATE TABLE IF NOT EXISTS sessions (
  id             BIGSERIAL PRIMARY KEY,
  server_host    TEXT        NOT NULL,
  server_port    INTEGER     NOT NULL DEFAULT 25565,
  -- The protocol actually spoken to the server. With ViaVersion this differs
  -- from the version the client was built against, and that distinction is the
  -- whole reason this bot can reach servers the old one could not.
  target_version TEXT,
  client         TEXT        NOT NULL DEFAULT 'azalea',
  bot_username   TEXT,
  started_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at       TIMESTAMPTZ,
  end_reason     TEXT
);

CREATE INDEX IF NOT EXISTS sessions_started_idx ON sessions (started_at DESC);
CREATE INDEX IF NOT EXISTS sessions_host_idx    ON sessions (server_host);

-- Refuse to run against a pre-r8 database rather than half-applying on top of
-- one. The logger calls this file on every start.
DO $$
BEGIN
  IF (SELECT c.relkind FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE n.nspname = 'public' AND c.relname = 'chat_messages') = 'p' THEN
    RAISE EXCEPTION 'chat_messages is still a table: this database predates r8. '
                    'Run deploy/migrate-r8.sh before starting this build.';
  END IF;
END $$;

-- Every name the logger has ever written, exactly once. Players, mobs
-- ("Zombie"), and whatever a death message named. Deliberately not `players`:
-- that table means "a real player we have seen" and drives the kill filters and
-- the unique-player count, so mob names must not land in it.
CREATE TABLE IF NOT EXISTS name_dict (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS name_dict_lower_uidx ON name_dict (lower(name));

CREATE TABLE IF NOT EXISTS players (
  uuid       UUID PRIMARY KEY,
  name       TEXT        NOT NULL,
  first_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One logical player per name. Real Mojang UUIDs win over name-based UUIDs;
-- the logger deletes extras on touch. Needed so Discord "players" totals are
-- unique names, not duplicate UUID rows.
CREATE UNIQUE INDEX IF NOT EXISTS players_name_lower_uidx ON players (lower(name));
ALTER TABLE players ADD COLUMN IF NOT EXISTS chat_rank TEXT;
-- Ties a player to the dictionary so "is this name a real player" is an int
-- join instead of lower(name) = lower(name) against a text index.
ALTER TABLE players ADD COLUMN IF NOT EXISTS name_id INTEGER;
CREATE UNIQUE INDEX IF NOT EXISTS players_name_id_uidx ON players (name_id);

-- Every name a UUID has been seen under. The old schema overwrote the name in
-- place, which lost the history the moment somebody renamed.
CREATE TABLE IF NOT EXISTS player_names (
  uuid     UUID        NOT NULL,
  name     TEXT        NOT NULL,
  seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (uuid, name)
);

-- 8,8,4,4,4,4,1,1 = 34 bytes of fixed columns with zero padding. Putting an
-- int4 between two 8-byte columns would silently cost 4 bytes on every row.
CREATE TABLE IF NOT EXISTS chat_messages_raw (
  id           BIGINT      NOT NULL,
  received_at  TIMESTAMPTZ NOT NULL,
  session_id   INTEGER,
  -- name_dict ids. NULL where the line named nobody.
  sender_id    INTEGER,
  -- Who the line is *about*, for lines with no sender: joined, left, died.
  subject_id   INTEGER,
  -- Who did the killing, for deaths phrased "... by X". May be a mob, so this
  -- points at name_dict, not players.
  killer_id    INTEGER,
  -- p | s | d (player / system / disguised)
  source       "char"      NOT NULL,
  -- c | w | j | l | d | a | s | u
  kind         "char"      NOT NULL,
  -- Chat/whisper: the message body only. Advancement: trailing [title] only.
  -- Death/join/leave: ''. Server/unknown: the line. Discord rebuilds display
  -- strings from kind + names when this is empty.
  plain_text   TEXT        NOT NULL DEFAULT ''
) PARTITION BY RANGE (received_at);

-- 8,8,4,4,1,1 = 26 bytes. player_uuid is 16 bytes and would repeat on every
-- row, so it is only stored where it disagrees with the canonical players.uuid
-- for that name; NULL costs nothing beyond the null bitmap already present.
CREATE TABLE IF NOT EXISTS player_events_raw (
  id           BIGINT      NOT NULL,
  occurred_at  TIMESTAMPTZ NOT NULL,
  session_id   INTEGER,
  player_id    INTEGER     NOT NULL,
  -- j | l | s (join / leave / snapshot)
  event_type   "char"      NOT NULL,
  -- t | c | r (tablist / chat / restart-synthesised leave)
  source       "char"      NOT NULL,
  player_uuid  UUID
) PARTITION BY RANGE (occurred_at);

CREATE SEQUENCE IF NOT EXISTS chat_messages_id_seq AS bigint OWNED BY chat_messages_raw.id;
CREATE SEQUENCE IF NOT EXISTS player_events_id_seq AS bigint OWNED BY player_events_raw.id;
ALTER TABLE chat_messages_raw ALTER COLUMN id SET DEFAULT nextval('chat_messages_id_seq');
ALTER TABLE player_events_raw ALTER COLUMN id SET DEFAULT nextval('player_events_id_seq');

CREATE INDEX IF NOT EXISTS chat_received_brin ON chat_messages_raw USING brin (received_at);
CREATE INDEX IF NOT EXISTS chat_sender_idx
  ON chat_messages_raw (sender_id, received_at DESC)
  WHERE sender_id IS NOT NULL AND kind IN ('c', 'w');
-- Deaths and advancements are a small slice of the table, so a partial index on
-- the subject stays small while still answering "what happened to X".
CREATE INDEX IF NOT EXISTS chat_subject_idx
  ON chat_messages_raw (subject_id, received_at DESC)
  WHERE subject_id IS NOT NULL AND kind IN ('d', 'a');

CREATE INDEX IF NOT EXISTS events_occurred_brin ON player_events_raw USING brin (occurred_at);
CREATE INDEX IF NOT EXISTS events_player_idx
  ON player_events_raw (player_id, occurred_at DESC)
  WHERE event_type IN ('j', 'l');

-- ---------------------------------------------------------------------------
-- Partition maintenance
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION r8_make_partitions(parent text, first_month date, last_month date)
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE
  m date;
  -- Children keep the logical name (chat_messages_2026_08), not the physical
  -- one (chat_messages_raw), so the partitions the swap renamed are the same
  -- ones this function later finds already present.
  prefix text := regexp_replace(parent, '_raw$', '');
BEGIN
  m := first_month;
  WHILE m <= last_month LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS %I PARTITION OF %I FOR VALUES FROM (%L) TO (%L)',
      prefix || '_' || to_char(m, 'YYYY_MM'),
      parent,
      m::timestamp AT TIME ZONE 'UTC',
      (m + interval '1 month')::timestamp AT TIME ZONE 'UTC'
    );
    m := (m + interval '1 month')::date;
  END LOOP;
END;
$fn$;

-- Monthly children so inserts never miss a partition.
CREATE OR REPLACE FUNCTION ensure_month_partitions() RETURNS void
LANGUAGE plpgsql AS $fn$
DECLARE i int; m date;
BEGIN
  FOR i IN -1..2 LOOP
    m := (date_trunc('month', timezone('UTC', now())) + (i || ' months')::interval)::date;
    PERFORM r8_make_partitions('chat_messages_raw', m, m);
    PERFORM r8_make_partitions('player_events_raw', m, m);
  END LOOP;
END;
$fn$;

SELECT ensure_month_partitions();

-- The closed-day archive is zstd-compressed, so the extension is required.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'zstd') THEN
    RAISE EXCEPTION 'the zstd extension is missing - run deploy/install-pgzstd.sh';
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Archive: closed days packed one zstd frame per column
--
-- A chat row costs ~135 bytes on disk for ~40 bytes of text, and TOAST never
-- compresses a row that small (measured: lz4 + toast_tuple_target saved 1%).
-- Packing each column of a batch into one array makes it a single varlena,
-- which zstd then compresses - 10.6x on a real month of 6b6t. Arrays rather
-- than a serialised blob so Postgres owns the encoding and it is lossless.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS chat_archive (
  bucket      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- The UTC day this bucket covers. A busy day spans several buckets.
  day         DATE        NOT NULL,
  -- Derived, so anything written against the r10 month archive still reads.
  month       DATE        NOT NULL GENERATED ALWAYS AS (date_trunc('month', day::timestamp)::date) STORED,
  n           INTEGER     NOT NULL,
  -- Bucket bounds, so a caller can skip whole buckets without decompressing.
  min_at      TIMESTAMPTZ NOT NULL,
  max_at      TIMESTAMPTZ NOT NULL,
  -- The highest source id packed here. The delete that follows a pack is
  -- bounded by this rather than by time, so a row that arrives for this day
  -- after the pack keeps a higher id and is left alone instead of vanishing.
  max_id      BIGINT      NOT NULL,
  -- Every name_dict id this bucket mentions in any role, sorted and distinct.
  -- Without it a per-player query over a year of history decompresses every
  -- bucket to find the handful that name them.
  name_ids    INTEGER[]   NOT NULL,
  ids         BYTEA       NOT NULL,
  received_at BYTEA       NOT NULL,
  session_id  BYTEA       NOT NULL,
  sender_id   BYTEA       NOT NULL,
  subject_id  BYTEA       NOT NULL,
  killer_id   BYTEA       NOT NULL,
  source      BYTEA       NOT NULL,
  kind        BYTEA       NOT NULL,
  plain_text  BYTEA       NOT NULL
);

CREATE TABLE IF NOT EXISTS events_archive (
  bucket      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day         DATE        NOT NULL,
  month       DATE        NOT NULL GENERATED ALWAYS AS (date_trunc('month', day::timestamp)::date) STORED,
  n           INTEGER     NOT NULL,
  min_at      TIMESTAMPTZ NOT NULL,
  max_at      TIMESTAMPTZ NOT NULL,
  max_id      BIGINT      NOT NULL,
  name_ids    INTEGER[]   NOT NULL,
  ids         BYTEA       NOT NULL,
  occurred_at BYTEA       NOT NULL,
  session_id  BYTEA       NOT NULL,
  player_id   BYTEA       NOT NULL,
  event_type  BYTEA       NOT NULL,
  source      BYTEA       NOT NULL,
  player_uuid BYTEA       NOT NULL
);

-- The payload is already a zstd frame; TOAST must not try to compress it again.
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.relname AS tbl, a.attname AS col
    FROM pg_class c
    JOIN pg_attribute a ON a.attrelid = c.oid
    JOIN pg_type t ON t.oid = a.atttypid
    WHERE c.relname IN ('chat_archive', 'events_archive')
      AND a.attnum > 0 AND NOT a.attisdropped AND t.typname = 'bytea'
  LOOP
    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I SET STORAGE EXTERNAL', r.tbl, r.col);
  END LOOP;
END $$;

-- An r10 database has a chat_archive without these columns, and the CREATE
-- TABLE IF NOT EXISTS above will have quietly left it alone. Check before the
-- indexes rather than after: `CREATE INDEX ... (day)` on the old table fails
-- with "column day does not exist", which says nothing about what to do.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_attribute
     WHERE attrelid = 'chat_archive'::regclass AND attname = 'day' AND NOT attisdropped
  ) THEN
    RAISE EXCEPTION 'chat_archive predates r11 - run deploy/migrate-r11.sh before starting this build.';
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS chat_archive_time_idx    ON chat_archive   (min_at, max_at);
CREATE INDEX IF NOT EXISTS chat_archive_day_idx     ON chat_archive   (day);
CREATE INDEX IF NOT EXISTS chat_archive_month_idx   ON chat_archive   (month);
CREATE INDEX IF NOT EXISTS chat_archive_names_idx   ON chat_archive   USING gin (name_ids);
CREATE INDEX IF NOT EXISTS events_archive_time_idx  ON events_archive (min_at, max_at);
CREATE INDEX IF NOT EXISTS events_archive_day_idx   ON events_archive (day);
CREATE INDEX IF NOT EXISTS events_archive_month_idx ON events_archive (month);
CREATE INDEX IF NOT EXISTS events_archive_names_idx ON events_archive USING gin (name_ids);

