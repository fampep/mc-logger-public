-- Standby loggers. Every logger upserts its own row every HEARTBEAT_SECS; a
-- standby writes nothing while a *primary* row for the same host is both
-- connected and fresh. Presence alone cannot be inferred from recent writes:
-- a quiet server looks identical to a dead logger, and the standby would take
-- over and duplicate every row once the primary came back.
CREATE TABLE IF NOT EXISTS logger_heartbeats (
  instance     TEXT PRIMARY KEY,
  role         TEXT        NOT NULL DEFAULT 'primary',
  server_host  TEXT        NOT NULL,
  session_id   BIGINT,
  bot_username TEXT,
  connected    BOOLEAN     NOT NULL DEFAULT false,
  writing      BOOLEAN     NOT NULL DEFAULT false,
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS logger_heartbeats_host_idx
  ON logger_heartbeats (server_host, role, updated_at DESC);

-- The server's own player count, parsed straight from its tab-list header
