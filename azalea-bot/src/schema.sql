CREATE OR REPLACE VIEW logger_stats AS
  SELECT true AS id,
         COALESCE(sum(messages), 0)::bigint AS messages,
         COALESCE(sum(chat),     0)::bigint AS chat,
         COALESCE(sum(joins),    0)::bigint AS joins,
         COALESCE(sum(leaves),   0)::bigint AS leaves,
         COALESCE(sum(deaths),   0)::bigint AS deaths,
         COALESCE(sum(kills),    0)::bigint AS kills,
         COALESCE(sum(goals),    0)::bigint AS goals
  FROM stats_daily;

-- Kill/death tally per player, PvP only. Served from the rollup, so it no
-- longer scans every death line in history.
CREATE OR REPLACE VIEW kill_leaderboard AS
  SELECT nd.name,
         sum(d.kills)::bigint      AS kills,
         sum(d.pvp_deaths)::bigint AS deaths
  FROM player_daily d
  JOIN name_dict nd ON nd.id = d.player_id
  GROUP BY nd.name
  HAVING sum(d.kills) > 0 OR sum(d.pvp_deaths) > 0
  ORDER BY kills DESC, deaths ASC;

-- ---------------------------------------------------------------------------
-- Presence as state, not as a scan of the whole event log
-- ---------------------------------------------------------------------------

-- Two loggers can share one database (6b6t lobby + survival), so presence is
-- decided per session and only then unioned by name: a leave seen in the lobby
-- must not hide a player still on the survival tab list. Only sessions that are
-- still open count — a disconnect produces no RemovePlayer for everyone left on
-- the tab list, so closing the session retires those rows.
CREATE TABLE IF NOT EXISTS player_presence (
  session_id  INTEGER     NOT NULL,
  player_id   INTEGER     NOT NULL,
  server_host TEXT        NOT NULL,
  present     BOOLEAN     NOT NULL,
  at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, player_id)
);
CREATE INDEX IF NOT EXISTS player_presence_live_idx
  ON player_presence (server_host, player_id) WHERE present;

CREATE OR REPLACE VIEW online_now AS
  SELECT DISTINCT ON (pp.server_host, lower(nd.name))
         pp.server_host, nd.name AS player_name, p.uuid AS player_uuid, pp.at AS occurred_at
  FROM player_presence pp
  JOIN name_dict nd ON nd.id = pp.player_id
  JOIN sessions s ON s.id = pp.session_id AND s.ended_at IS NULL
  LEFT JOIN players p ON p.name_id = pp.player_id
  WHERE pp.present
  ORDER BY pp.server_host, lower(nd.name), pp.at DESC;

