-- unnest() over several arrays at once zips them, so a row comes back exactly
-- as it went in. Element NULLs survive; only a wholly NULL array would drop a
-- row, which is why every array column above is NOT NULL.
CREATE OR REPLACE VIEW chat_archive_rows AS
  SELECT u.* FROM chat_archive a,
    LATERAL unnest(
      convert_from(zstd_decompress(a.ids),         'UTF8')::bigint[],
      convert_from(zstd_decompress(a.received_at), 'UTF8')::timestamptz[],
      convert_from(zstd_decompress(a.session_id),  'UTF8')::int[],
      convert_from(zstd_decompress(a.sender_id),   'UTF8')::int[],
      convert_from(zstd_decompress(a.subject_id),  'UTF8')::int[],
      convert_from(zstd_decompress(a.killer_id),   'UTF8')::int[],
      convert_from(zstd_decompress(a.source),      'UTF8')::"char"[],
      convert_from(zstd_decompress(a.kind),        'UTF8')::"char"[],
      convert_from(zstd_decompress(a.plain_text),  'UTF8')::text[]
    ) AS u(id, received_at, session_id, sender_id, subject_id, killer_id,
           source, kind, plain_text);

CREATE OR REPLACE VIEW events_archive_rows AS
  SELECT u.* FROM events_archive a,
    LATERAL unnest(
      convert_from(zstd_decompress(a.ids),         'UTF8')::bigint[],
      convert_from(zstd_decompress(a.occurred_at), 'UTF8')::timestamptz[],
      convert_from(zstd_decompress(a.session_id),  'UTF8')::int[],
      convert_from(zstd_decompress(a.player_id),   'UTF8')::int[],
      convert_from(zstd_decompress(a.event_type),  'UTF8')::"char"[],
      convert_from(zstd_decompress(a.source),      'UTF8')::"char"[],
      convert_from(zstd_decompress(a.player_uuid), 'UTF8')::uuid[]
    ) AS u(id, occurred_at, session_id, player_id, event_type, source, player_uuid);

-- ---------------------------------------------------------------------------
-- Accessors: one definition of "the log between these two timestamps"
--
-- Everything that reads history goes through these rather than naming a
-- physical table, because which side of the hot window a row is on is exactly
-- the detail a caller should not have to know. The bounds test on min_at/max_at
-- is what keeps the archive half cheap: buckets outside the range are skipped
-- whole, without a decompress.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION chat_rows_between(lo timestamptz, hi timestamptz)
RETURNS TABLE (id bigint, received_at timestamptz, session_id int, sender_id int,
               subject_id int, killer_id int, source "char", kind "char", plain_text text)
LANGUAGE sql STABLE PARALLEL SAFE AS $fn$
  SELECT c.id, c.received_at, c.session_id, c.sender_id, c.subject_id,
         c.killer_id, c.source, c.kind, c.plain_text
  FROM chat_messages_raw c
  WHERE c.received_at >= lo AND c.received_at < hi
  UNION ALL
  SELECT r.id, r.received_at, r.session_id, r.sender_id, r.subject_id,
         r.killer_id, r.source, r.kind, r.plain_text
  FROM chat_archive a
  CROSS JOIN LATERAL unnest(
      convert_from(zstd_decompress(a.ids),         'UTF8')::bigint[],
      convert_from(zstd_decompress(a.received_at), 'UTF8')::timestamptz[],
      convert_from(zstd_decompress(a.session_id),  'UTF8')::int[],
      convert_from(zstd_decompress(a.sender_id),   'UTF8')::int[],
      convert_from(zstd_decompress(a.subject_id),  'UTF8')::int[],
      convert_from(zstd_decompress(a.killer_id),   'UTF8')::int[],
      convert_from(zstd_decompress(a.source),      'UTF8')::"char"[],
      convert_from(zstd_decompress(a.kind),        'UTF8')::"char"[],
      convert_from(zstd_decompress(a.plain_text),  'UTF8')::text[]
    ) AS r(id, received_at, session_id, sender_id, subject_id, killer_id,
           source, kind, plain_text)
  WHERE a.max_at >= lo AND a.min_at < hi
    AND r.received_at >= lo AND r.received_at < hi
$fn$;

CREATE OR REPLACE FUNCTION event_rows_between(lo timestamptz, hi timestamptz)
RETURNS TABLE (id bigint, occurred_at timestamptz, session_id int, player_id int,
               event_type "char", source "char", player_uuid uuid)
