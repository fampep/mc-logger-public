-- ---------------------------------------------------------------------------
-- Packing
--
-- A day is not a partition, so packing DELETEs its rows rather than dropping a
-- table, bounded by the highest id the pack saw. Bounding by time instead would
-- take out anything that landed between the INSERT and the DELETE.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION archive_chat_day(target_day date, batch int DEFAULT 20000)
RETURNS TABLE (packed bigint, buckets bigint, before_bytes bigint, after_bytes bigint)
LANGUAGE plpgsql AS $fn$
DECLARE
  lo timestamptz := target_day::timestamp AT TIME ZONE 'UTC';
  hi timestamptz := (target_day + 1)::timestamp AT TIME ZONE 'UTC';
  src_rows bigint; new_rows bigint; src_sum text; new_sum text;
  sz_before bigint; cap_id bigint;
BEGIN
  IF target_day >= timezone('UTC', now())::date THEN
    RAISE EXCEPTION 'refusing to archive % - that day is still being written', target_day;
  END IF;
  IF EXISTS (SELECT 1 FROM chat_archive WHERE day = target_day) THEN
    RAISE EXCEPTION 'chat_archive already holds %', target_day;
  END IF;

  -- 28 bytes is the per-row tuple header plus item pointer. Without it the
  -- "before" figure is column data alone and flatters the ratio by ~40%.
  SELECT count(*), max(id), coalesce(sum(pg_column_size(c.*)), 0) + 28 * count(*)
    INTO src_rows, cap_id, sz_before
    FROM chat_messages_raw c
   WHERE c.received_at >= lo AND c.received_at < hi;

  IF src_rows = 0 THEN
    RETURN;
  END IF;

  SELECT md5(string_agg(sig, '' ORDER BY sig)) INTO src_sum FROM (
    SELECT id::text||'|'||received_at::text||'|'||coalesce(session_id::text,'')||'|'
           ||coalesce(sender_id::text,'')||'|'||coalesce(subject_id::text,'')||'|'
           ||coalesce(killer_id::text,'')||'|'||source::text||'|'||kind::text||'|'||plain_text AS sig
    FROM chat_messages_raw
    WHERE received_at >= lo AND received_at < hi AND id <= cap_id) s;

  -- Ordering by sender first is what makes the text column compress: one
  -- player's lines sit together, and zstd's window is then full of their
  -- vocabulary rather than the whole server's.
  INSERT INTO chat_archive (day, n, min_at, max_at, max_id, name_ids, ids, received_at,
                            session_id, sender_id, subject_id, killer_id, source, kind, plain_text)
  SELECT target_day, count(*), min(received_at), max(received_at), max(id),
         (SELECT coalesce(array_agg(DISTINCT nid ORDER BY nid), '{}')
            FROM unnest(array_agg(sender_id) || array_agg(subject_id) || array_agg(killer_id)) AS t(nid)
           WHERE nid IS NOT NULL),
         zstd_compress(convert_to((array_agg(id          ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(received_at ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(session_id  ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(sender_id   ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(subject_id  ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(killer_id   ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(source      ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(kind        ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(plain_text  ORDER BY sender_id, received_at, id))::text, 'UTF8'), NULL, 19)
  FROM (
    SELECT *, (row_number() OVER (ORDER BY received_at, id) - 1) / batch AS b
    FROM chat_messages_raw
    WHERE received_at >= lo AND received_at < hi AND id <= cap_id
  ) x
  GROUP BY b;

  SELECT count(*) INTO new_rows FROM chat_archive_rows
   WHERE received_at >= lo AND received_at < hi;

  SELECT md5(string_agg(sig, '' ORDER BY sig)) INTO new_sum FROM (
    SELECT id::text||'|'||received_at::text||'|'||coalesce(session_id::text,'')||'|'
           ||coalesce(sender_id::text,'')||'|'||coalesce(subject_id::text,'')||'|'
           ||coalesce(killer_id::text,'')||'|'||source::text||'|'||kind::text||'|'||plain_text AS sig
    FROM chat_archive_rows WHERE received_at >= lo AND received_at < hi) s;

  IF new_rows <> src_rows OR new_sum IS DISTINCT FROM src_sum THEN
    DELETE FROM chat_archive WHERE day = target_day;
    RAISE EXCEPTION 'archive of % did not match the source (% vs % rows, checksum %) - nothing deleted',
      target_day, src_rows, new_rows, CASE WHEN new_sum = src_sum THEN 'ok' ELSE 'MISMATCH' END;
  END IF;

  DELETE FROM chat_messages_raw
   WHERE received_at >= lo AND received_at < hi AND id <= cap_id;

  packed := src_rows;
  before_bytes := sz_before;
  SELECT count(*), coalesce(sum(pg_column_size(a.*)), 0) INTO buckets, after_bytes
    FROM chat_archive a WHERE a.day = target_day;
  RETURN NEXT;
END;
$fn$;

CREATE OR REPLACE FUNCTION archive_events_day(target_day date, batch int DEFAULT 20000)
RETURNS TABLE (packed bigint, buckets bigint, before_bytes bigint, after_bytes bigint)
LANGUAGE plpgsql AS $fn$
DECLARE
  lo timestamptz := target_day::timestamp AT TIME ZONE 'UTC';
  hi timestamptz := (target_day + 1)::timestamp AT TIME ZONE 'UTC';
  src_rows bigint; new_rows bigint; src_sum text; new_sum text;
  sz_before bigint; cap_id bigint;
BEGIN
  IF target_day >= timezone('UTC', now())::date THEN
    RAISE EXCEPTION 'refusing to archive % - that day is still being written', target_day;
  END IF;
  IF EXISTS (SELECT 1 FROM events_archive WHERE day = target_day) THEN
    RAISE EXCEPTION 'events_archive already holds %', target_day;
  END IF;

  SELECT count(*), max(id), coalesce(sum(pg_column_size(e.*)), 0) + 28 * count(*)
    INTO src_rows, cap_id, sz_before
    FROM player_events_raw e
   WHERE e.occurred_at >= lo AND e.occurred_at < hi;

  IF src_rows = 0 THEN
    RETURN;
  END IF;

  SELECT md5(string_agg(sig, '' ORDER BY sig)) INTO src_sum FROM (
    SELECT id::text||'|'||occurred_at::text||'|'||coalesce(session_id::text,'')||'|'
           ||player_id::text||'|'||event_type::text||'|'||source::text||'|'
           ||coalesce(player_uuid::text,'') AS sig
    FROM player_events_raw
    WHERE occurred_at >= lo AND occurred_at < hi AND id <= cap_id) s;

  INSERT INTO events_archive (day, n, min_at, max_at, max_id, name_ids, ids, occurred_at,
                              session_id, player_id, event_type, source, player_uuid)
  SELECT target_day, count(*), min(occurred_at), max(occurred_at), max(id),
         (SELECT coalesce(array_agg(DISTINCT nid ORDER BY nid), '{}')
            FROM unnest(array_agg(player_id)) AS t(nid) WHERE nid IS NOT NULL),
         zstd_compress(convert_to((array_agg(id          ORDER BY player_id, occurred_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(occurred_at ORDER BY player_id, occurred_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(session_id  ORDER BY player_id, occurred_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(player_id   ORDER BY player_id, occurred_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(event_type  ORDER BY player_id, occurred_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(source      ORDER BY player_id, occurred_at, id))::text, 'UTF8'), NULL, 19),
         zstd_compress(convert_to((array_agg(player_uuid ORDER BY player_id, occurred_at, id))::text, 'UTF8'), NULL, 19)
  FROM (
    SELECT *, (row_number() OVER (ORDER BY occurred_at, id) - 1) / batch AS b
    FROM player_events_raw
    WHERE occurred_at >= lo AND occurred_at < hi AND id <= cap_id
  ) x
  GROUP BY b;

  SELECT count(*) INTO new_rows FROM events_archive_rows
   WHERE occurred_at >= lo AND occurred_at < hi;

  SELECT md5(string_agg(sig, '' ORDER BY sig)) INTO new_sum FROM (
    SELECT id::text||'|'||occurred_at::text||'|'||coalesce(session_id::text,'')||'|'
           ||player_id::text||'|'||event_type::text||'|'||source::text||'|'
           ||coalesce(player_uuid::text,'') AS sig
    FROM events_archive_rows WHERE occurred_at >= lo AND occurred_at < hi) s;

  IF new_rows <> src_rows OR new_sum IS DISTINCT FROM src_sum THEN
    DELETE FROM events_archive WHERE day = target_day;
    RAISE EXCEPTION 'archive of % did not match the source (% vs % rows, checksum %) - nothing deleted',
      target_day, src_rows, new_rows, CASE WHEN new_sum = src_sum THEN 'ok' ELSE 'MISMATCH' END;
  END IF;

  DELETE FROM player_events_raw
   WHERE occurred_at >= lo AND occurred_at < hi AND id <= cap_id;

  packed := src_rows;
  before_bytes := sz_before;
  SELECT count(*), coalesce(sum(pg_column_size(a.*)), 0) INTO buckets, after_bytes
    FROM events_archive a WHERE a.day = target_day;
  RETURN NEXT;
END;
$fn$;

-- Drop month partitions that are empty and cannot receive anything again.
-- Once every day of a month is archived its partition is an empty shell.
CREATE OR REPLACE FUNCTION drop_empty_partitions()
RETURNS TABLE (dropped text)
LANGUAGE plpgsql AS $fn$
DECLARE r record; n bigint; this_month date := date_trunc('month', timezone('UTC', now()))::date;
BEGIN
  FOR r IN
    SELECT c.relname AS part, parent.relname AS parent
    FROM pg_class c
    JOIN pg_inherits i ON i.inhrelid = c.oid
    JOIN pg_class parent ON parent.oid = i.inhparent
    WHERE parent.relname IN ('chat_messages_raw', 'player_events_raw')
    ORDER BY c.relname
  LOOP
    -- chat_messages_2026_07 -> 2026-07-01
    CONTINUE WHEN to_date(right(r.part, 7), 'YYYY_MM') >= this_month;
    EXECUTE format('SELECT count(*) FROM %I', r.part) INTO n;
    CONTINUE WHEN n > 0;
    EXECUTE format('DROP TABLE %I', r.part);
    dropped := r.part;
    RETURN NEXT;
  END LOOP;
END;
$fn$;

-- ---------------------------------------------------------------------------
-- The driver
--
-- keep_days counts calendar days in UTC *including today*, so keep_days => 7 on
-- the 19th keeps the 13th through the 19th and packs everything on or before
-- the 12th. Anything already packed is skipped, which makes this safe to run
-- from cron as often as you like.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION archive_closed_days(keep_days int DEFAULT 7, batch int DEFAULT 20000)
RETURNS TABLE (kind text, day date, packed bigint, buckets bigint,
               before_bytes bigint, after_bytes bigint)
LANGUAGE plpgsql AS $fn$
DECLARE
  cutoff date := timezone('UTC', now())::date - (keep_days - 1);
  d date;
  res record;
BEGIN
  IF keep_days < 1 THEN
    RAISE EXCEPTION 'keep_days must be at least 1 - the current day is never archivable';
  END IF;

  FOR d IN
    SELECT DISTINCT (received_at AT TIME ZONE 'UTC')::date AS dd
    FROM chat_messages_raw
    WHERE received_at < cutoff::timestamp AT TIME ZONE 'UTC'
    ORDER BY 1
  LOOP
    CONTINUE WHEN EXISTS (SELECT 1 FROM chat_archive WHERE chat_archive.day = d);
    FOR res IN SELECT * FROM archive_chat_day(d, batch) LOOP
      kind := 'chat'; day := d;
      packed := res.packed; buckets := res.buckets;
      before_bytes := res.before_bytes; after_bytes := res.after_bytes;
      RETURN NEXT;
    END LOOP;
  END LOOP;

  FOR d IN
    SELECT DISTINCT (occurred_at AT TIME ZONE 'UTC')::date AS dd
    FROM player_events_raw
    WHERE occurred_at < cutoff::timestamp AT TIME ZONE 'UTC'
    ORDER BY 1
  LOOP
    CONTINUE WHEN EXISTS (SELECT 1 FROM events_archive WHERE events_archive.day = d);
    FOR res IN SELECT * FROM archive_events_day(d, batch) LOOP
      kind := 'events'; day := d;
      packed := res.packed; buckets := res.buckets;
      before_bytes := res.before_bytes; after_bytes := res.after_bytes;
      RETURN NEXT;
    END LOOP;
  END LOOP;

  PERFORM drop_empty_partitions();
END;
$fn$;

