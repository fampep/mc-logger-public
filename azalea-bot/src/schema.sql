CREATE OR REPLACE VIEW session_stats AS
  SELECT server_host,
         client,
         count(*)                                                            AS sessions,
         round(avg(EXTRACT(EPOCH FROM (ended_at - started_at)))::numeric, 1) AS avg_secs,
