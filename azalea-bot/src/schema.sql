CREATE TABLE IF NOT EXISTS stats_daily (
  day      DATE   PRIMARY KEY,
  messages BIGINT NOT NULL DEFAULT 0,
  chat     BIGINT NOT NULL DEFAULT 0,
  joins    BIGINT NOT NULL DEFAULT 0,
  leaves   BIGINT NOT NULL DEFAULT 0,
  deaths   BIGINT NOT NULL DEFAULT 0,
  kills    BIGINT NOT NULL DEFAULT 0,
  goals    BIGINT NOT NULL DEFAULT 0
);

-- Recompute a closed date range from the raw log. Past days never change, so
-- the logger only ever refreshes today and yesterday.
CREATE OR REPLACE FUNCTION refresh_stats_daily(lo date, hi date)
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE lo_ts timestamptz; hi_ts timestamptz;
BEGIN
  lo_ts := lo::timestamp AT TIME ZONE 'UTC';
  hi_ts := (hi + 1)::timestamp AT TIME ZONE 'UTC';

  DELETE FROM stats_daily WHERE day >= lo AND day <= hi;

  INSERT INTO stats_daily (day, messages, chat, joins, leaves, deaths, kills, goals)
  SELECT day,
         sum(messages), sum(chat), sum(joins), sum(leaves),
         sum(deaths), sum(kills), sum(goals)
  FROM (
    SELECT (c.received_at AT TIME ZONE 'UTC')::date AS day,
           count(*)                                                         AS messages,
           count(*) FILTER (WHERE c.kind IN ('c', 'w'))                     AS chat,
           0::bigint AS joins, 0::bigint AS leaves,
           count(*) FILTER (WHERE c.kind = 'd')                             AS deaths,
           count(*) FILTER (WHERE c.kind = 'd' AND c.killer_id IS NOT NULL) AS kills,
           count(*) FILTER (WHERE c.kind = 'a')                             AS goals
    FROM chat_rows_between(lo_ts, hi_ts) c
    GROUP BY 1
    UNION ALL
    SELECT (e.occurred_at AT TIME ZONE 'UTC')::date,
           0, 0,
           count(*) FILTER (WHERE e.event_type = 'j'),
           count(*) FILTER (WHERE e.event_type = 'l'),
           0, 0, 0
    FROM event_rows_between(lo_ts, hi_ts) e
    GROUP BY 1
  ) parts
  GROUP BY day;
END;
$fn$;

CREATE OR REPLACE FUNCTION refresh_player_daily(lo date, hi date)
RETURNS void LANGUAGE plpgsql AS $fn$
DECLARE lo_ts timestamptz; hi_ts timestamptz;
BEGIN
  lo_ts := lo::timestamp AT TIME ZONE 'UTC';
  hi_ts := (hi + 1)::timestamp AT TIME ZONE 'UTC';

  DELETE FROM player_daily WHERE day >= lo AND day <= hi;

  INSERT INTO player_daily
    (day, player_id, messages, deaths, pvp_deaths, kills, advancements, joins, leaves, playtime_secs)
  SELECT day, player_id,
         sum(messages)::int, sum(deaths)::int, sum(pvp_deaths)::int, sum(kills)::int,
         sum(advancements)::int, sum(joins)::int, sum(leaves)::int, sum(playtime_secs)::int
  FROM (
    -- what a player said
    SELECT (c.received_at AT TIME ZONE 'UTC')::date AS day, c.sender_id AS player_id,
           count(*) AS messages, 0 AS deaths, 0 AS pvp_deaths, 0 AS kills,
           0 AS advancements, 0 AS joins, 0 AS leaves, 0 AS playtime_secs
    FROM chat_rows_between(lo_ts, hi_ts) c
    WHERE c.kind IN ('c', 'w') AND c.sender_id IS NOT NULL
    GROUP BY 1, 2

    UNION ALL
    -- what happened to a player
    SELECT (c.received_at AT TIME ZONE 'UTC')::date, c.subject_id,
           0,
           count(*) FILTER (WHERE c.kind = 'd'),
           count(*) FILTER (WHERE c.kind = 'd' AND kp.name_id IS NOT NULL),
           0,
           count(*) FILTER (WHERE c.kind = 'a'),
           0, 0, 0
    FROM chat_rows_between(lo_ts, hi_ts) c
    LEFT JOIN players kp ON kp.name_id = c.killer_id
    WHERE c.kind IN ('d', 'a') AND c.subject_id IS NOT NULL
    GROUP BY 1, 2

    UNION ALL
    -- kills, PvP only: the killer has to be a name we know as a real player
    SELECT (c.received_at AT TIME ZONE 'UTC')::date, c.killer_id,
           0, 0, 0, count(*), 0, 0, 0, 0
    FROM chat_rows_between(lo_ts, hi_ts) c
    JOIN players kp ON kp.name_id = c.killer_id
    WHERE c.kind = 'd' AND c.subject_id IS NOT NULL
    GROUP BY 1, 2

    UNION ALL
    -- comings and goings
    SELECT (e.occurred_at AT TIME ZONE 'UTC')::date, e.player_id,
           0, 0, 0, 0, 0,
           count(*) FILTER (WHERE e.event_type = 'j'),
           count(*) FILTER (WHERE e.event_type = 'l'),
           0
    FROM event_rows_between(lo_ts, hi_ts) e
    WHERE e.event_type IN ('j', 'l')
    GROUP BY 1, 2

    UNION ALL
    -- time in game, attributed to the day it was spent on rather than the day
    -- the session started, so a session across midnight lands on both.
    SELECT g.day, g.player_id, 0, 0, 0, 0, 0, 0, 0,
           EXTRACT(EPOCH FROM sum(
             least(spell.fin, (g.day + 1)::timestamp AT TIME ZONE 'UTC')
             - greatest(spell.beg, g.day::timestamp AT TIME ZONE 'UTC')))::int
    FROM (
      SELECT player_id,
             occurred_at AS beg,
             lead(occurred_at) OVER (PARTITION BY player_id ORDER BY occurred_at, id) AS fin,
             event_type,
             lead(event_type) OVER (PARTITION BY player_id ORDER BY occurred_at, id) AS fin_type
      -- One day either side, so a join just before the window and its leave
      -- just after both still bound the spell inside it.
      FROM event_rows_between(lo_ts - interval '1 day', hi_ts + interval '1 day')
      WHERE event_type IN ('j', 'l')
    ) spell
    CROSS JOIN LATERAL generate_series(
      greatest((spell.beg AT TIME ZONE 'UTC')::date, lo),
      least((spell.fin AT TIME ZONE 'UTC')::date, hi),
      interval '1 day') AS g_day(d)
    CROSS JOIN LATERAL (SELECT g_day.d::date AS day, spell.player_id) g
    WHERE spell.event_type = 'j' AND spell.fin_type = 'l' AND spell.fin > spell.beg
    GROUP BY g.day, g.player_id
  ) parts
  GROUP BY day, player_id;
END;
$fn$;

-- The shape the per-row triggers used to maintain, now a sum over one row per
